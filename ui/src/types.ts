/**
 * Frostcap UI data model.
 *
 * This is the editor-friendly view of the Rust `Project` (see contract.ts for
 * the wire shapes). backend.ts converts in both directions:
 *  - times are milliseconds on the video clock (`t`, `start`, `end`);
 *  - positions are normalized 0..1 of the canvas (Rust stores physical pixels);
 *  - clips are the kept ranges (Rust stores the complement as `trims`).
 * See docs/UI.md for every mapping rule.
 */
import type { WireCaptureSource, WireExportPreset, WireKeyCapture, WireLegacyPreset, WireOutputPreset, WireProject } from "./contract";

export type Ms = number;

// ---------------------------------------------------------------- sources

/** `allDisplays`: every monitor as one canvas (only listed when the backend can encode it). */
export type SourceKind = "display" | "window" | "region" | "allDisplays";

export interface Rect {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface CaptureSource {
  /** Unique key for React and selection, e.g. "monitor:\\.\DISPLAY1" or "window:1234". */
  id: string;
  kind: SourceKind;
  name: string;
  width: number;
  height: number;
  app?: string | null;
  primary?: boolean;
  refreshRate?: number;
  thumbnail?: string | null;
  /** What start_recording expects. */
  wire: WireCaptureSource;
}

export interface CameraInfo {
  id: string;
  name: string;
}

// -------------------------------------------------------------- recording

export interface StartRecordingOptions {
  source: CaptureSource;
  fps: number;
  cursor: boolean;
  mic: boolean;
  systemAudio: boolean;
  /** Key capture mode (privacy: default off). */
  keys: WireKeyCapture;
  /** Camera id from list_cameras, `default`, or null for no webcam. */
  camera: string | null;
  /** Record window titles (privacy opt-in; backend default off). */
  windowTitles?: boolean;
}

export type RecordingStatus = "idle" | "recording" | "paused";

export interface RecordingState {
  status: RecordingStatus;
  elapsedMs: Ms;
  projectDir: string | null;
}

export interface RecordingResult {
  projectPath: string;
  durationMs: Ms;
  warnings: string[];
}

export interface Issue {
  /** disk_full, source_gone, no_h264, invalid_path, invalid_project, permission, io, internal, and `cancelled` (the user declined a native confirmation). */
  code: string;
  message: string;
}

// ---------------------------------------------------------------- project

export interface CursorSample {
  t: Ms;
  x: number;
  y: number;
}

export type MouseButton = "left" | "right" | "middle";

export interface ClickEvent {
  t: Ms;
  x: number;
  y: number;
  button: MouseButton;
  state: "down" | "up";
}

export interface KeyEvent {
  t: Ms;
  vk: number;
  label: string;
  modifiers: { ctrl: boolean; shift: boolean; alt: boolean; win: boolean };
}

export interface FocusChange {
  t: Ms;
  windowId: number;
  /** Empty unless the user opted in to window titles. */
  title: string;
  /** Normalized to the canvas. */
  rect: Rect;
}

/** Same names as the Rust enum. */
export type Easing = "linear" | "easeInOutCubic" | "easeOutQuint" | "spring";

export interface ZoomSegment {
  id: string;
  start: Ms;
  end: Ms;
  cx: number;
  cy: number;
  scale: number;
  easing: Easing;
  /** Zoom-in and zoom-out transition length (each). */
  transitionMs: Ms;
  /** Generated by auto-zoom (Rust `origin: "auto"`). */
  auto?: boolean;
}

/** A kept range of the recording; the output is the clips in order. */
export interface Clip {
  id: string;
  start: Ms;
  end: Ms;
}

export interface CaptionCue {
  id: string;
  start: Ms;
  end: Ms;
  text: string;
}

export interface GradientBackground {
  /** Preset id, or "custom". */
  id: string;
  angle: number;
  stops: string[];
}

export type ZoomPreset = "gentle" | "balanced" | "snappy";
export type WindowFrame = "none" | "minimal" | "windows" | "macos" | "laptop" | "phone";
export type WebcamShape = "circle" | "rounded" | "square";
export type Corner = "top-left" | "top-right" | "bottom-left" | "bottom-right";

export type AnnotationKind = "arrow" | "text" | "rect" | "ellipse" | "highlight" | "spotlight" | "blur" | "pixelate";

/** Drawn over the screen content (coordinates 0..1 of the content, so they follow the zoom). Mirrors Rust `Annotation`. */
export interface Annotation {
  id: string;
  kind: AnnotationKind;
  start: Ms;
  end: Ms;
  /** Box (or arrow start), 0..1. */
  x: number;
  y: number;
  w: number;
  h: number;
  /** Arrow end. */
  x2: number;
  y2: number;
  color: string;
  strokeWidth: number;
  fill: boolean;
  text: string;
  fontSize: number;
  opacity: number;
  /** blur radius / pixel block size */
  strength: number;
  /** spotlight darkening */
  dim: number;
  cornerRadius: number;
  fadeMs: Ms;
}

/** Playback speed on the source clock (cuts apply first). Mirrors Rust `edits.speed`. */
export interface SpeedSegment {
  id: string;
  start: Ms;
  end: Ms;
  /** 0.25..4 */
  speed: number;
}

export type WebcamBackgroundKind = "none" | "color" | "gradient" | "image" | "blur";

export interface WebcamStyle {
  enabled: boolean;
  shape: WebcamShape;
  size: number;
  position: Corner;
  /** Fraction of the output height. */
  margin: number;
  /** px at 1080p */
  borderWidth: number;
  borderColor: string;
  mirror: boolean;
  brightness: number;
  contrast: number;
  saturation: number;
  shadow: number;
  chromaKey: { enabled: boolean; color: string; similarity: number; smoothness: number; spill: number };
  /** Replaces the keyed-out area; only applies while chromaKey.enabled. */
  background: { kind: WebcamBackgroundKind; color: string; gradient: string; image?: string; blur: number };
}

export interface BackgroundImage {
  /** Basename inside the project folder (from import_background). */
  file: string;
  fit: "cover" | "contain";
  /** 0..100 */
  blur: number;
}

export interface ProjectStyle {
  /** Rust `style.background` (CSS gradient string). */
  background: GradientBackground;
  /** Percent of output size, 0..40 (Rust `padding` fraction × 100). */
  padding: number;
  /** Output px (Rust `cornerRadius`). */
  radius: number;
  /** 0..100 (Rust `shadow` × 100). */
  shadow: number;
  /** UI-only (stored in `edits.ui`). */
  frame: WindowFrame;
  zoom: {
    preset: ZoomPreset;
    /** Defaults for new manual segments. */
    scale: number;
    easing: Easing;
    transitionMs: Ms;
  };
  cursor: {
    /** UI-only. */
    visible: boolean;
    /** Rust `cursorSmoothing` switch; effective smoothing = smooth ? smoothing : 0. */
    smooth: boolean;
    /** Amount 0..1 (Rust `cursor.smoothing`). */
    smoothing: number;
    /** Rust `cursorScale`. */
    size: number;
    /** Rust `showClicks`. */
    clickRipple: boolean;
    /** UI-only. */
    motionBlur: number;
  };
  /** Rust `showKeys`. */
  keys: { show: boolean };
  webcam: WebcamStyle;
  /** Optional picture behind the framed screen; absent when unset. */
  backgroundImage?: BackgroundImage;
  audio: {
    noiseGate: boolean;
    noiseGateThreshold: number;
    highPass: boolean;
    highPassHz: number;
    normalize: boolean;
    targetLufs: number;
    micGain: number;
    systemGain: number;
  };
  captions: { enabled: boolean; fontSize: number; position: "bottom" | "top"; background: boolean };
}

export interface MediaRef {
  /** File name relative to the project folder. */
  file: string;
  /** URL the webview can load (asset protocol), or null in the browser demo. */
  url: string | null;
}

export interface AudioTrackInfo extends MediaRef {
  /** Where the first sample sits on the video clock (may be negative). */
  offsetMs: Ms;
  sampleRate: number;
  channels: number;
  durationMs: Ms;
}

export interface ProjectMedia {
  /** Project folder. */
  dir: string;
  screen: MediaRef;
  webcam: MediaRef | null;
  mic: AudioTrackInfo | null;
  systemAudio: AudioTrackInfo | null;
  width: number;
  height: number;
  fps: number;
  durationMs: Ms;
}

export interface Project {
  name: string;
  /** ISO-8601 */
  createdAt: string;
  media: ProjectMedia;
  cursor: CursorSample[];
  clicks: ClickEvent[];
  keys: KeyEvent[];
  focus: FocusChange[];
  zoomSegments: ZoomSegment[];
  annotations: Annotation[];
  speed: SpeedSegment[];
  clips: Clip[];
  captions: CaptionCue[];
  style: ProjectStyle;
  /** System cursor is baked into screen.mp4; the editor does not redraw it. */
  cursorBaked: boolean;
  /**
   * The project exactly as loaded. Tracks are never edited, so saving reuses
   * `wire.tracks` by reference (exact round-trip, no 400k-sample copies).
   */
  wire: WireProject;
}

export interface RecentProject {
  path: string;
  name: string;
  durationMs: Ms;
  /** ISO-8601 */
  createdAt: string;
  width: number;
  height: number;
  interrupted?: boolean;
  thumbnail?: string | null;
}

// ----------------------------------------------------------------- export

export type AspectPreset = "16:9" | "9:16" | "1:1";
/** `av1` (AV1 + AAC in MP4) is only offered when `encoder_capabilities().formats` lists it. */
export type ExportFormat = "mp4" | "gif" | "av1";
export type ExportPresetId = WireLegacyPreset;
export type OutputPreset = WireOutputPreset;

export interface ExportRequest {
  /** Project folder. */
  path: string;
  /** Output preset, or "raw" for the unedited recording. */
  preset: WireExportPreset;
  /** Must come from pick_save_path (the backend rejects other targets). */
  outPath: string;
  jobId: string;
}

export interface ExportResult {
  jobId: string;
  outPath: string;
  bytes: number;
  baked: boolean;
}

export interface ExportProgress {
  jobId: string;
  /** Only for export_batch: which job of the batch. */
  jobIndex?: number;
  progress: number;
  stage: string;
}

export interface RegionSelection {
  monitorId: string;
  rect: Rect;
  screenRect: Rect;
}

export interface HotkeyChord {
  action: "startStop" | "pauseResume";
  chord: string;
  registered: boolean;
}